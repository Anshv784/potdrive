#!/usr/bin/env bun
// Writes contracts/test/Fixtures.sol from the real SDK, so the Solidity tests run against the
// exact bytes PotDrive produces: UnixFS roots, a leaf, malformed variants and a wallet-format
// sr25519 permit.   bun scripts/contract-fixtures.ts
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import * as dagPB from "@ipld/dag-pb";
import { UnixFS } from "ipfs-unixfs";
import { CID } from "multiformats/cid";
import { create as mh } from "multiformats/hashes/digest";
import { cryptoWaitReady, sr25519PairFromSeed, sr25519Sign } from "@polkadot/util-crypto";
import { stringToU8a, u8aWrapBytes } from "@polkadot/util";
import { bytesToHex, getAddress } from "viem";
import { buildDirectory, buildFileDag } from "../sdk/src/dag";
import { cidFor, contentHash, RAW } from "../sdk/src/cid";
import { permitText, reviveAddressOf } from "../sdk/src/permit";

await cryptoWaitReady();
const hex = (b: Uint8Array) => bytesToHex(b);
const bytesOf = (n: number, seed: number) => Uint8Array.from({ length: n }, (_, i) => (i * 31 + seed * 7) & 0xff);

// A 2,500-byte file in 1,000-byte chunks: three raw leaves and a dag-pb root.
const file = buildFileDag(bytesOf(2500, 1), 1000);
const fileRoot = file.blocks.at(-1)!;

// A website-shaped directory: a sub-folder and two files, names sorted as UnixFS requires.
const dir = buildDirectory([
  { path: "index.html", bytes: bytesOf(300, 2) },
  { path: "assets/app.js", bytes: bytesOf(1800, 3) },
  { path: "about.html", bytes: bytesOf(120, 4) },
]);
const dirRoot = dir.blocks.at(-1)!;
const dirNode = dagPB.decode(dirRoot.bytes);
const dirSize = dirNode.Links.reduce((s, l) => s + Number(l.Tsize ?? 0), 0);

// Malformed roots the contract must refuse.
const leaves = file.leaves;
const encodeFile = (blockSizes: bigint[], links: { Hash: CID; Tsize: number }[]) =>
  dagPB.encode({ Data: new UnixFS({ type: "file", blockSizes }).marshal(), Links: links.map((l) => ({ ...l, Name: "" })) as never });
const lyingSizes = encodeFile(
  [1000n, 1000n, 900n], // the last leaf is 500 bytes
  leaves.map((l) => ({ Hash: l.cid, Tsize: l.bytes.length })),
);
const sha = CID.createV1(RAW, mh(0x12, new Uint8Array(32).fill(7)));
const wrongHash = encodeFile([1000n], [{ Hash: sha, Tsize: 1000 }]);
// dag-pb refuses to encode unsorted links, so splice the fields: a PBNode is just its fields in a row.
const one = (Name: string, seed: number) => dagPB.encode({ Links: [{ Name, Hash: cidFor(bytesOf(10, seed)), Tsize: 10 }] });
const dirData = dagPB.encode({ Data: new UnixFS({ type: "directory" }).marshal(), Links: [] });
const unsortedDir = new Uint8Array([...one("b.txt", 5), ...one("a.txt", 6), ...dirData]);

// A permit exactly as a Polkadot wallet signs it.
const REGISTRY = "0x00000000000000000000000000000000000000ad" as const;
const pair = sr25519PairFromSeed(new Uint8Array(32).fill(42));
const meta = { isPrivate: false, name: "deck.pdf", mime: "application/pdf", parent: `0x${"0".repeat(64)}` as const };
const extra = "upload key: 5Fake…\nbytes: 2500";
const text = permitText({ root: file.root, meta, registry: REGISTRY, nonce: 0, deadline: 5000, extra });
const signature = sr25519Sign(u8aWrapBytes(stringToU8a(text)), pair);

const sol = `// SPDX-License-Identifier: MIT
// Generated by scripts/contract-fixtures.ts from the PotDrive SDK. Do not edit.
pragma solidity ^0.8.28;

library Fixtures {
    // File: 2,500 bytes, three raw leaves of 1,000 / 1,000 / 500
    bytes internal constant FILE_NODE = hex"${hex(fileRoot.bytes).slice(2)}";
    bytes32 internal constant FILE_ROOT = ${contentHash(file.root)};
    string internal constant FILE_CID = "${file.root.toString()}";
    uint64 internal constant FILE_SIZE = ${file.size};
    uint32 internal constant FILE_CHUNKS = ${file.leaves.length};
    bytes internal constant LEAF_1 = hex"${hex(leaves[1].bytes).slice(2)}";

    // Directory: index.html, about.html and assets/app.js
    bytes internal constant DIR_NODE = hex"${hex(dirRoot.bytes).slice(2)}";
    bytes32 internal constant DIR_ROOT = ${contentHash(dir.root)};
    uint64 internal constant DIR_SIZE = ${dirSize};
    uint32 internal constant DIR_LINKS = ${dirNode.Links.length};

    // Malformed roots
    bytes internal constant LYING_SIZES = hex"${hex(lyingSizes).slice(2)}";
    bytes internal constant WRONG_HASH = hex"${hex(wrongHash).slice(2)}";
    bytes internal constant UNSORTED_DIR = hex"${hex(unsortedDir).slice(2)}";

    // Permit, signed over "<Bytes>" + PERMIT_TEXT + "</Bytes>" with a real sr25519 key
    address internal constant REGISTRY = ${getAddress(REGISTRY)};
    uint32 internal constant DEADLINE = 5000;
    bytes internal constant EXTRA = hex"${hex(stringToU8a(extra)).slice(2)}";
    bytes internal constant PERMIT_TEXT = hex"${hex(stringToU8a(text)).slice(2)}";
    bytes32 internal constant SIGNER = ${hex(pair.publicKey)};
    address internal constant SIGNER_ADDRESS = ${getAddress(reviveAddressOf(pair.publicKey))};
    bytes internal constant SIGNATURE = hex"${hex(signature).slice(2)}";
}
`;
await writeFile(resolve(import.meta.dir, "../contracts/test/Fixtures.sol"), sol);
console.log("contracts/test/Fixtures.sol");
